function drawGridViewer(grid) {
    var cellW = 22;
    var cellH = 12;
    var topY = 4;
    var bottomPadding = 2;
    var gridOffsetX = Math.floor(cellW / 2);
    var gridOffsetY = Math.floor(cellH / 2);
    var visibleCols = Math.max(1, Math.floor((displayWidth - 6 - gridOffsetX) / cellW));
    var visibleRows = Math.max(1, Math.min(grid.rowCount, Math.floor((displayHeight - topY - bottomPadding - gridOffsetY) / cellH)));
    var start = findStartCell(grid);

    var cursorR = start.r;
    var cursorC = start.c;
    var offsetR = 0;
    var offsetC = 0;
    var needsRedraw = true;

    function isNavigableCellAt(r, c) {
        var raw = grid.rows[r][c] || "";
        var text = normalizeCellForDisplay(raw);
        return raw === ROOT_MARKER || isLetterOrDigitCell(text);
    }

    function moveCursor(dr, dc) {
        var r = cursorR + dr;
        var c = cursorC + dc;

        while (r >= 0 && r < grid.rowCount && c >= 0 && c < grid.colCount) {
            if (isNavigableCellAt(r, c)) {
                cursorR = r;
                cursorC = c;
                return true;
            }
            r += dr;
            c += dc;
        }
        return false;
    }

    function moveToTopInColumn() {
        var r;
        for (r = 0; r < grid.rowCount; r++) {
            if (isNavigableCellAt(r, cursorC)) {
                cursorR = r;
                return true;
            }
        }
        return false;
    }

    function clampOffsets() {
        if (cursorR < offsetR) offsetR = cursorR;
        if (cursorR >= offsetR + visibleRows) offsetR = cursorR - visibleRows + 1;
        if (cursorC < offsetC) offsetC = cursorC;
        if (cursorC >= offsetC + visibleCols) offsetC = cursorC - visibleCols + 1;

        if (offsetR < 0) offsetR = 0;
        if (offsetC < 0) offsetC = 0;

        if (offsetR > Math.max(0, grid.rowCount - visibleRows)) {
            offsetR = Math.max(0, grid.rowCount - visibleRows);
        }
        if (offsetC > Math.max(0, grid.colCount - visibleCols)) {
            offsetC = Math.max(0, grid.colCount - visibleCols);
        }
    }

    while (true) {
        clampOffsets();

        if (needsRedraw) {
            var vr;
            var vc;
            display.fill(bgColor);
            display.drawRoundRect(1, 1, displayWidth - 2, displayHeight - 2, 4, priColor);
            display.setTextColor(priColor);
            display.setTextSize(1);

            for (vr = 0; vr < visibleRows; vr++) {
                var gr = offsetR + vr;
                if (gr >= grid.rowCount) {
                    break;
                }
                for (vc = 0; vc < visibleCols; vc++) {
                    var gc = offsetC + vc;
                    if (gc >= grid.colCount) {
                        break;
                    }

                    var x = 4 + gridOffsetX + vc * cellW;
                    var y = topY + gridOffsetY + vr * cellH;
                    var rawCell = grid.rows[gr][gc] || "";
                    var cellShiftY = rawCell === ROOT_MARKER ? -Math.floor(cellH / 2) : 0;
                    var drawY = y + cellShiftY;
                    var cellText = normalizeCellForDisplay(rawCell);
                    var isLetterCell = isLetterOrDigitCell(cellText);
                    var isSelected = gr === cursorR && gc === cursorC;
                    var contentColor = isSelected ? bgColor : priColor;

                    if (isSelected) {
                        fillCell(x, drawY, cellW - 2, cellH - 1, priColor);
                    }

                    if (isLetterCell) {
                        display.drawRect(x, drawY, cellW - 2, cellH - 1, isSelected ? secColor : priColor);
                    } else if (isSelected) {
                        display.drawRect(x, drawY, cellW - 2, cellH - 1, secColor);
                    }

                    if (rawCell === ROOT_MARKER) {
                        drawCenteredConnector("^", x, drawY, cellW, cellH, contentColor);
                    } else {
                        if (isLetterCell) {
                            var morse = getLastMorseSymbol(cellText);
                            if (morse === "." || morse === "-") {
                                drawLetterAndMorse(cellText, morse, x, drawY, cellW, cellH, contentColor);
                            } else {
                                var textX = x + Math.max(1, Math.floor((cellW - 2 - 6) / 2));
                                var textY = drawY + Math.max(0, Math.floor((cellH - 8) / 2));
                                drawBoldText(cellText, textX, textY, contentColor);
                            }
                        } else {
                            if (cellText === "-" || cellText === "|") {
                                drawCenteredConnector(cellText, x, drawY, cellW, cellH, secColor);
                            } else {
                                display.setTextColor(contentColor);
                                display.drawString(cellText, x + 2, drawY + 2);
                            }
                        }
                    }
                }
            }

            var selectedRaw = grid.rows[cursorR][cursorC] || "";
            var selectedText = normalizeCellForDisplay(selectedRaw);
            drawBottomLeftLabel("MORSE CODE");
            if (selectedRaw === ROOT_MARKER) {
                drawNavigationPreview();
            } else if (isLetterOrDigitCell(selectedText)) {
                drawSelectionPreview(selectedText, MORSE_TABLE[selectedText] || "");
            }

            needsRedraw = false;
        }

        if (keyboard.getNextPress()) {
            if (moveCursor(0, 1)) {
                needsRedraw = true;
            }
        } else if (keyboard.getPrevPress()) {
            if (moveCursor(0, -1)) {
                needsRedraw = true;
            }
        } else if (keyboard.getSelPress()) {
            if (moveCursor(1, 0) || moveToTopInColumn()) {
                needsRedraw = true;
            }
        } else if (keyboard.getEscPress()) {
            return;
        }

        delay(25);
    }
}

function renderBitmap(x, y, bitmap, width, height, color, bgColor) {
    var data = new Uint8Array(bitmap);
    var byteWidth = Math.floor((width + 7) / 8);

    for (var j = 0; j < height; j++) {
        for (var i = 0; i < width; i++) {
            var byteIndex = j * byteWidth + Math.floor(i / 8);
            var bitIndex = i % 8;
            var pixel = (data[byteIndex] >> bitIndex) & 1;

            if (pixel) {
                display.drawPixel(x + i, y + j, color);
            } else if (bgColor !== undefined) {
                display.drawPixel(x + i, y + j, bgColor);
            }
        }
    }
}

